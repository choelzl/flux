def _backend_rows() -> list[str]:
    """The evaluator-backend table, generated from the live registry: every name in
    `available_backends()` with the first line of its adapter module's docstring.
    Import only -- no instantiation, no tool probing -- so the output is identical on
    every machine and the freshness guard stays meaningful."""
    import importlib

    from flux_cli.registry import available_backends

    rows = ["## Evaluator backends", "",
            "Sixteen adapters behind one ABI; pass any of these as `backend`:", "",
            "| backend | what it is |", "|---|---|"]
    for name in available_backends():
        try:
            mod = importlib.import_module(f"flux_evaluator_{name}")
            doc = (mod.__doc__ or "").strip().split("\n")[0].rstrip(".")
        except Exception as exc:  # noqa: BLE001 -- a missing adapter is a row, not a crash
            doc = f"(module unavailable: {type(exc).__name__})"
        rows.append(f"| `{name}` | {doc} |")
    return rows


def generate() -> dict[Path, str]:
    """Render every catalog page, `{absolute path: content}`, writing nothing."""
    from flux_omni.catalog import build_catalog

    catalog = build_catalog()

    unmapped = sorted(catalog.keys() - GROUPS.keys())
    dead = sorted(GROUPS.keys() - catalog.keys())
    if unmapped or dead:
        raise SystemExit(
            "GROUPS in website/generate_catalog.py disagrees with the live catalog -- "
            f"unmapped tools: {unmapped or 'none'}; mapped but no longer registered: "
            f"{dead or 'none'}. Assign or remove them, then regenerate."
        )

    pages: dict[Path, str] = {}
    for slug, (title, intro) in PAGES.items():
        specs = [catalog[n] for n in sorted(catalog) if GROUPS[n] == slug]
        body = "\n\n".join(_render_tool(spec) for spec in specs)
        extras = ""
        if slug == "evaluate":
            extras += "\n".join(_backend_rows()) + "\n\n"
        if slug in EXAMPLES:
            extras += EXAMPLES[slug] + "\n"
        content = f"{_HEADER}# {title}\n\n{intro}\n\n{extras}{body}\n"
        pages[_CATALOG_DIR / f"{slug}.md"] = content
    return pages


def main() -> None:
    _CATALOG_DIR.mkdir(parents=True, exist_ok=True)
    for path, content in generate().items():
        path.write_text(content)
        print(f"wrote {path}", file=sys.stderr)


if __name__ == "__main__":
    main()
