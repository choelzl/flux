def _cell(text: str) -> str:
    """One markdown table cell: pipes escaped, newlines flattened, and the first-sentence
    truncation's dangling ', e.g.' fragment dropped (the catalog cuts arg docs at the first
    sentence; on a page the stub invites an example that never comes)."""
    import re

    text = " ".join(str(text).split()).replace("|", "\\|")
    return re.sub(r"[,;]?\s*\(?\s*e\.g\.$", "", text).strip()


def _param_rows(params, *, with_default: bool) -> list[str]:
    head = ("| parameter | type | default | what it is |", "|---|---|---|---|") \
        if with_default else ("| parameter | type | what it is |", "|---|---|---|")
    rows = list(head)
    for p in params:
        default = f" `{_cell(repr(p.default))}` |" if with_default else ""
        rows.append(f"| `{p.name}` | `{_cell(p.annotation)}` |{default} {_cell(p.doc)} |")
    return rows


def _render_tool(spec) -> str:
    """One tool, shaped for a reader: heading, summary, required up front, optionals folded."""
    lines = [f"## {spec.name}", "", spec.summary]
    required = [p for p in spec.params if p.required]
    optional = [p for p in spec.params if not p.required]
    if required:
        lines += ["", *_param_rows(required, with_default=False)]
    if optional:
        n = len(optional)
        lines += ["", f'??? note "{n} optional parameter{"s" if n > 1 else ""}"', ""]
        lines += [f"    {row}" for row in _param_rows(optional, with_default=True)]
    return "\n".join(lines)


