"""Generate the documentation site's tool-catalog pages from the live MCP surface.

The site's "modules" section is not hand-written: `flux_omni.catalog.build_catalog()` replays
`FluxTool.setup()`'s own registrations (the same introspection the omni loop plans over), and
this script renders each `ToolSpec` into grouped Markdown pages under `website/docs/catalog/`.
A hand-maintained catalog page would rot exactly the way D95/D96 measured; this one cannot,
because `flux/tests/unit/test_site_catalog_freshness.py` regenerates it and diffs.

The one thing introspection cannot supply is grouping: `ToolSpec` carries no topic, so `GROUPS`
below assigns every tool to a page by name, and `generate()` refuses to run when the mapping and
the live catalog disagree in either direction -- a newly registered tool forces a conscious
grouping choice here, the same discipline as `test_mcp_surface_parity.py`.

The rendering is the site's own, not `ToolSpec.render()` (D389): that flat bullet form is the
shape a MODEL copies arguments out of, and on a page it reads as a wall of text. A reader gets
each tool as a heading (so the page's table of contents lists them), its summary, the required
parameters in a small table, and the optional ones -- which dominate, several tools take 15+ --
folded into a collapsible table with their defaults. Same introspected content, reader-shaped.

Run it from the dev shell (importing flux_mcp needs the flake's PYTHONPATH):

    cd flux && nix develop --command python3 ../website/generate_catalog.py
"""

