def run_generation_arms(log) -> dict:
    from flux_chia_nodes.generate_rtl import flux_generate_rtl_module
    from flux_knowledge.retrieval import knowledge_lookup

    hits = knowledge_lookup(
        "true precision multiplier accumulator intermediate width clamp",
        standard_id="design-guidance", k=2)
    guidance = "\n\n".join(h.chunk.text for h in hits)
    records = []
    for arm, arm_guidance in (("guided", guidance), ("plain", None)):
        for spec in _SPECS:
            for rep in range(REPS_A):
                t0 = time.perf_counter()
                result = flux_generate_rtl_module(
                    spec, guidance=arm_guidance, max_repair_attempts=3)
                rec = {
                    "comparison": "A-generation", "arm": arm, "spec": spec["id"],
                    "rep": rep, "success": result.success, "attempts": result.attempts,
                    "wall_s": round(time.perf_counter() - t0, 1),
                }
                records.append(rec)
                log(json.dumps(rec))
    return _summarize_a(records)


def _summarize_a(records) -> dict:
    out = {"records": records, "arms": {}}
    for arm in ("guided", "plain"):
        rows = [r for r in records if r["arm"] == arm]
        ok = [r for r in rows if r["success"]]
        out["arms"][arm] = {
            "runs": len(rows),
            "successes": len(ok),
            "success_rate": round(len(ok) / len(rows), 3),
            "mean_attempts_on_success": round(
                statistics.mean(r["attempts"] for r in ok), 2) if ok else None,
            "per_spec_successes": {
                s["id"]: sum(1 for r in rows if r["spec"] == s["id"] and r["success"])
                for s in _SPECS
            },
        }
    return out


# -- comparison B: fact-fed proposing -------------------------------------------------------


def _base_arch():
    import yaml

    return yaml.safe_load(
        (FLUX_ROOT / "core/ir/architecture/examples/simple-npu-1d-v1.yaml").read_text())


def _chain_workload():
    sys.path.insert(0, str(FLUX_ROOT / "tests/integration"))
    import _helpers

    return _helpers.chain_workload()


def _campaign_doc(workload, base_arch, ident, strategy):
    return {
        "schema_version": "0.1.0",
        "id": ident,
        "objectives": [{"metric": "latency_cycles", "direction": "minimize"}],
        "mode": "pareto",
        "workload": {"inline": workload},
        "base_arch": {"inline": base_arch},
        "backends": {"screening": "zigzag"},
        "search": {"kind": "composition_width", "widths": [4, 8, 16, 32]},
        "strategy": strategy,
        "budget": {"evaluations": BUDGET_B},
    }


def run_proposer_arms(log, workdir: Path) -> dict:
    from chia.models.ollama import OllamaLLM

    from flux_chia_nodes import flux_mine_knowledge
    from flux_knowledge_mining import render_facts_for_prompt
    from flux_search_campaign import parse_objective, run_campaign_steps
    from flux_store import CampaignStore

    workload, base_arch = _chain_workload(), _base_arch()

    # the PRIOR campaign the facts come from: grid over {8,16}, fully measured (zigzag)
    prior_doc = _campaign_doc(workload, base_arch, "exp/prior/v1",
                              {"kind": "grid", "seed": 0})
    prior_doc["search"]["widths"] = [8, 16]
    prior_doc["budget"]["evaluations"] = 16
    prior_db = str(workdir / "prior.db")
    store = CampaignStore(prior_db)
    cid, _ = store.start_campaign(prior_doc, parse_objective(prior_doc).objective_hash)
    assert run_campaign_steps(store, cid).status in ("done", "budget_exhausted")
    facts = flux_mine_knowledge(campaign_db_paths=[prior_db])["facts"]
    knowledge = render_facts_for_prompt(facts)
    log(f"# prior campaign mined: {len(facts)} fact(s)")

    class _Proposer:
        def __init__(self) -> None:
            self._llm = OllamaLLM(model=MODEL)

        def propose(self, prompt: str) -> str:
            return self._llm.prompt(prompt).result

    records = []
    for arm, arm_knowledge in (("facts", knowledge), ("cold", None)):
        for rep in range(REPS_B):
            doc = _campaign_doc(
                workload, base_arch, f"exp/{arm}/rep{rep}/v1",
                {"kind": "agentic", "seed": rep, "llm_model": MODEL})
            db = str(workdir / f"{arm}-{rep}.db")
            store = CampaignStore(db)
            cid, _ = store.start_campaign(doc, parse_objective(doc).objective_hash)
            run_campaign_steps(store, cid, make_llm=lambda model: _Proposer(),
                               knowledge=arm_knowledge)
            trials = store.ok_trials(cid, phase="screen")
            best = min(t.result.value_of("latency_cycles") for t in trials)
            picked = [tuple(sorted(t.candidate["assignment"].items())) for t in trials]
            rec = {
                "comparison": "B-proposing", "arm": arm, "rep": rep,
                "trials": len(trials), "best_latency": best,
                "found_3232": (("mm0", 32), ("mm1", 32)) in [tuple(p) for p in picked],
                "picked": [dict(p) for p in picked],
            }
            records.append(rec)
            log(json.dumps(rec))
    return _summarize_b(records)


def _summarize_b(records) -> dict:
    out = {"records": records, "arms": {}}
    for arm in ("facts", "cold"):
        rows = [r for r in records if r["arm"] == arm]
        out["arms"][arm] = {
            "campaigns": len(rows),
            "mean_best_latency": round(statistics.mean(r["best_latency"] for r in rows), 1),
            "best_latencies": [r["best_latency"] for r in rows],
            "found_3232": sum(1 for r in rows if r["found_3232"]),
        }
    return out


def main() -> None:
    import tempfile

    def log(line: str) -> None:
        print(line, flush=True)

    # Emitted before anything else so the log is self-describing: a result whose model is not in
    # the record cannot be compared against a later one, which is how this experiment's first
    # write-up came to name its model only in prose.
    log(f"# model: {MODEL}")
    log("# comparison A: guidance-fed generation (this is the slow half)")
    a = run_generation_arms(log)
    log("A-SUMMARY " + json.dumps(a["arms"], indent=2))

    log("# comparison B: fact-fed proposing")
    with tempfile.TemporaryDirectory() as d:
        b = run_proposer_arms(log, Path(d))
    log("B-SUMMARY " + json.dumps(b["arms"], indent=2))


if __name__ == "__main__":
    main()
