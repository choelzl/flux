"""Does knowledge feeding measurably help? (docs/decisions.md D248)

Two controlled comparisons, each arm differing in EXACTLY one variable:

  A. RTL generation (D244's open question): the same four precision-trap specs, generated by
     real qwen and verified by real Verilator, REPS times per arm — with retrieved
     design-guidance chunks in the prompt vs without. Metrics: verified-success rate within
     the repair budget, and mean attempts on successes.

  B. Agentic campaign proposing (D245's open question): the same composition search space
     ({4,8,16,32}^2 per-layer widths on the 8:1-imbalanced chain), a budget of 4 screening
     trials out of 16 points, real qwen proposing, REPS campaigns per arm — with mined facts
     from a prior measured campaign in the prompt vs cold. Metric: best screened latency found
     within the budget (lower is better), and whether the known optimum (32,32) was found.

Run inside the dev shell:  python3 experiments/knowledge_efficacy.py
Writes JSONL records + a summary to stdout; the report belongs in
flux/docs/knowledge-efficacy-report.md with the decision log recording the conclusion.
"""

