# The model is a VARIABLE of this experiment, not a constant of it: the report's own "not
# established" section names larger generator/proposer models as the untested residue, so the
# harness has to be re-runnable against one. Whatever is set here is what the report must name.
MODEL = os.environ.get("FLUX_LLM_MODEL", "qwen3.8:latest")
REPS_A = 3   # per spec per arm
REPS_B = 4   # campaigns per arm
BUDGET_B = 4  # screening trials per campaign (of 16 points)

