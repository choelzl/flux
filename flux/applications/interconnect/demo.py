def design_guidance(db: str) -> tuple[str, list]:
    """Everything the local model is allowed to know, from the two knowledge surfaces this repo
    already has (docs/decisions.md D270), kept as the different kinds of claim they are.

    CURATED: the referenceable IP catalog (what each family costs, when to use it, its published
    conditions and their scope) plus the retrieved `design-guidance` chunks on fabric selection.
    MEASURED: facts mined from this campaign's own store — what was actually built and what it
    came out at. A model handed only the second has no vocabulary; handed only the first it has
    no evidence about THIS silicon.
    """
    from flux_chia_nodes import flux_ip_catalog, flux_knowledge_lookup, flux_mine_knowledge

    catalog = flux_ip_catalog(interface="obi", status="constructible")
    lines = ["Interconnect IP available, with what is known about each:"]
    for ip in catalog["ip"]:
        lines.append(f"- {ip['title']}: {ip['summary']} Cost: {ip['cost_shape']}. "
                     f"Use when: {ip['when_to_use']}. Limits: {ip['known_limits']}")
        if ip["measured_here"]:
            lines.append(f"  Measured in this repo: {ip['measured_here']}")
    for query in ("interconnect fabric selection arity frequency",
                  "routing policy path diversity throughput"):
        for hit in flux_knowledge_lookup(query, standard_id="design-guidance", k=1)[:1]:
            lines.append("- " + str(hit["chunk"].get("text", ""))[:600])

    facts = flux_mine_knowledge(campaign_db_paths=[db]).get("facts", [])
    from flux_knowledge_mining import render_facts_for_prompt

    return fit_to_budget("\n".join(lines), facts, render_facts_for_prompt,
                         budget=KNOWLEDGE_BUDGET_CHARS)


