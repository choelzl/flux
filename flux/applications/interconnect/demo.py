def llm_round(db: str, round_no: object, budget: int) -> dict:
    """A round where the LOCAL MODEL proposes the fabrics (docs/decisions.md D269).

    The enumerated rounds can only widen within families someone wrote down; this one lets a
    the local model propose structures directly, having been handed the problem, this
    repo's own measured arity-to-frequency table, and everything measured so far. Nothing
    leaves the machine, and the model is on the PROPOSING side only: every fabric it names is
    built by the real constructor, routed constructively, screened, placed and simulated with
    the correctness checks of D268, exactly like an enumerated one. A bad proposal costs an
    evaluation and is recorded as a fallback; it cannot produce a wrong answer.
    """
    from flux_chia_nodes import (
        flux_campaign_frontier,
        flux_campaign_start,
        flux_campaign_status,
        flux_campaign_step,
    )

    # The grant covers the proposals PLUS the rungs they earn, and the strategy is capped at
    # the proposal count — otherwise screening eats the whole grant and the round, having
    # proposed a dozen fabrics, measures none of them.
    grant = budget + ESCALATION_HEADROOM
    doc = objective_document(
        family="hybrid", budget=grant, round_no=round_no,
        strategy={"kind": "generative_interconnect", "seed": 0, "llm_model": LLM_MODEL,
                  "max_proposals": budget},
    )
    doc["search"].pop("extra_variants", None)  # nothing named: the model does the naming
    started = flux_campaign_start(doc, db)
    print(f"\n=== round {round_no}: LOCAL LLM proposes {budget} fabrics ({LLM_MODEL})")
    guidance, facts = design_guidance(db)
    print(f"    handed the model {len(guidance):,} chars of curated guidance and "
          f"{len(facts)} measured facts from this run")
    report = flux_campaign_step(db, started["campaign_id"], max_trials=grant,
                                escalation_parallelism=ESCALATION_WORKERS,
                                calibration_db_path=_calibration_path(db),
                                knowledge_facts=facts,
                                knowledge_text=guidance)
    status = flux_campaign_status(db, started["campaign_id"])
    frontier = flux_campaign_frontier(db, started["campaign_id"], include_contenders=True)
    print(f"    {report['status']}: {status['trial_counts']}, "
          f"{len(frontier['contenders'])} contenders escalated")
    return {"campaign_id": started["campaign_id"], "report": report, "space": 0}


def run_round(db: str, round_no: int, family: str, budget: int | None) -> dict:
    """One campaign, driven entirely through the agent-surface tools."""
    from flux_chia_nodes import (
        flux_campaign_frontier,
        flux_campaign_start,
        flux_campaign_status,
        flux_campaign_step,
    )
    from flux_interconnect import enumerate_space

    space = enumerate_space(CLIENTS, BANKS, WIDTH_BITS, max_stages=4, breadth="wide",
                            max_candidates=5000, families=[family])
    doc = objective_document(family=family, round_no=round_no,
                             budget=budget or len(space) + ESCALATION_HEADROOM)
    extra = doc["search"].get("extra_variants") or []
    started = flux_campaign_start(doc, db)
    print(f"\n=== round {round_no}: the {family} family "
          f"-> {len(space) + len(extra)} candidates, budget {doc['budget']['evaluations']}")
    report = flux_campaign_step(db, started["campaign_id"], max_trials=10_000,
                                escalation_parallelism=ESCALATION_WORKERS,
                                calibration_db_path=_calibration_path(db))
    status = flux_campaign_status(db, started["campaign_id"])
    frontier = flux_campaign_frontier(db, started["campaign_id"], include_contenders=True)
    print(f"    {report['status']}: {status['trial_counts']}, "
          f"{len(frontier['contenders'])} contenders escalated, "
          f"budget left {status['remaining_budget'].get('evaluations')}")
    return {"campaign_id": started["campaign_id"], "report": report,
            "space": len(space) + len(extra)}


