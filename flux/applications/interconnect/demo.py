def objective_document(*, family: str = "staged", budget: int = 200, round_no: int = 1,
                       strategy: dict | None = None,
                       variants: list[dict] | None = None) -> dict:
    """The DSE for one round: every knob visible, nothing hidden in code."""
    return {
        "schema_version": "0.1.0",
        "id": (f"demo/interconnect-{CLIENTS}c-{BANKS}b-{WIDTH_BITS}bit/"
               f"round{round_no}-{family}/v1"),
        # Area against achievable concurrency. Latency is REPORTED per candidate but is not
        # an objective: as a screened metric it lets the 1-stage crossbar dominate the
        # contender set before timing is known, and its 1-cycle latency is a mirage if the
        # fabric cannot clock (measured: the direct crossbar closes at 483 MHz).
        "objectives": [
            {"metric": "area_mm2", "direction": "minimize", "measured_at": "escalation"},
            {"metric": "throughput_words_per_cycle", "direction": "maximize"},
            # The screen's own structural stand-in for area, and it is here because leaving it
            # out made the whole search degenerate: `area_mm2` exists only after escalation, so
            # a screen front built from throughput and wiring alone is won outright by the plain
            # crossbar, which maximises throughput at zero inter-stage wiring. It dominated every
            # round, exactly ONE contender escalated each time, and it then failed the 600 MHz
            # constraint - so the rounds measured nothing and the demo reported a frontier built
            # entirely from whatever the store already held. `mux_bits` restores the trade-off at
            # screen time, where it costs nothing. It earns the role by measurement rather than
            # plausibility: against the 23 fabrics in this repo's own store that have both a
            # screened `mux_bits` and a placed `area_mm2`, Pearson r = 0.95.
            {"metric": "mux_bits", "direction": "minimize"},
            # Wiring is a real cost the cell area omits, so it is an objective rather than a
            # footnote — otherwise a fabric of many tiny switches wins by hiding its wires.
            {"metric": "interstage_link_bits", "direction": "minimize"},
        ],
        "mode": "pareto",
        # The fabric serves this traffic; the workload document is required by the ABI and
        # hashed for provenance even though a fabric has no einsum to run.
        "workload": {"inline": {
            "schema_version": "0.1.0", "id": f"demo/{CLIENTS}-clients-{WIDTH_BITS}b",
            "ops": [{"id": "fabric_traffic", "kind": "compute_kernel",
                     "attrs": {"clients": CLIENTS, "banks": BANKS,
                               "width_bits": WIDTH_BITS}}],
        }},
        "base_arch": {"inline": {
            "schema_version": "0.1.0", "id": "demo/fabric",
            "tech": {"node": "n7", "pdk_class": "open"},
            "hierarchy": [
                {"level": "bank", "class": "memory",
                 "attrs": {"size_kb": BANK_ROWS * WIDTH_BITS / 8 / 1024,
                           "word_width_bits": WIDTH_BITS}},
            ],
        }},
        "backends": {"screening": "interconnect_struct", "escalation": ["interconnect_phys"]},
        # The PROBLEM, not a list of answers: Flux enumerates the topology space from
        # (clients, banks, width) itself — every interesting intermediate rank, every ordered
        # pair of ranks for 3-stage fabrics (which is what expresses asymmetric stages like
        # 4-then-7), and the radix-R networks the port count admits (docs/decisions.md D262).
        "search": {
            # The FULL depth and breadth, always: those two dials never partitioned anything,
            # every scope they described was a subset of the widest one (D308). What partitions
            # the space is the FAMILY, so that is what a round selects.
            "kind": "interconnect_topology", "clients": CLIENTS, "banks": BANKS,
            "width_bits": WIDTH_BITS, "max_stages": 4, "breadth": "wide",
            # A round built from NAMED variants enumerates nothing: perturbation defines its own
            # space against an incumbent, and enumerating a family beside it would drown the
            # neighbours it exists to measure.
            "families": [] if variants is not None else [family],
            # Discovery covers the monolithic-stage and radix-R families. A PARALLEL-SWITCH
            # fabric is a different structure — "first stage 4x4, second stage 7x8" means
            # seven 4x4 switches then four 7x8 switches, not one 28->28 crossbar — so it is
            # named explicitly and measured alongside everything the search found.
            "extra_variants": list(variants) if variants is not None else [
                {"kind": "xbar_staged", "clients": CLIENTS, "banks": BANKS,
                 "width_bits": WIDTH_BITS,
                 "stages": [{"switches": 7, "in": 4, "out": 4},
                            {"switches": 4, "in": 7, "out": 8}]},
                {"kind": "xbar_staged", "clients": CLIENTS, "banks": BANKS,
                 "width_bits": WIDTH_BITS,
                 "stages": [{"switches": 4, "in": 7, "out": 7},
                            {"switches": 7, "in": 4, "out": 5}]},
            ],
        },
        "strategy": strategy or {"kind": "grid", "seed": 0},
        # Screening a topology is instant in tool terms but still spends one evaluation from
        # the grant, so the grant covers the discovered space plus the physical rungs the
        # contenders earn (see ESCALATION_HEADROOM). The latch is real and has fired twice: at
        # 32 the campaign stopped mid-screen, and at a flat 400 the widest round spent
        # everything on screening and measured nothing at all.
        "budget": {"evaluations": budget},
        # The hard requirement: anything that cannot clock at 600 MHz is not a candidate,
        # whatever its area. Checked where fmax exists (the physical rung); screening trials
        # legally lack it and are not judged on it.
        "constraints": [
            {"kind": "metric_min", "metric": "fmax_mhz", "min": TARGET_MHZ,
             "measured_at": "escalation"},
            # Full concurrency is a REQUIREMENT, not a preference: the clients access the banks
            # at the same time, so a fabric whose narrowest point carries fewer than all of
            # them cannot serve the stated problem however cheap it is. Checked at SCREEN,
            # where the capacity is structural and free, so the search never spends a
            # place-and-route on a fabric that was disqualified by its own dimensions (D283).
            {"kind": "metric_min", "metric": "max_throughput_words_per_cycle",
             "min": CLIENTS, "measured_at": "screen"},
        ],
    }


def bank_area_mm2() -> tuple[float, str]:
    """The memory the fabric serves, characterized by real CACTI and scaled to 7nm with the
    published-bitcell floor (docs/decisions.md D255/D256) — reported alongside the fabric so
    the interconnect's share of total silicon is visible."""
    from flux_evaluator_cacti.adapter import CactiEvaluator, run_cacti
    from flux_evaluator_cacti.architecture_translator import architecture_ir_to_sram_spec
    from flux_evaluator_cacti.scaling import measure_area_efficiency, scale_area_mm2

    size_kb = BANK_ROWS * WIDTH_BITS / 8 / 1024
    arch = {"id": "bank", "tech": {"node": "n32"},
            "hierarchy": [{"level": "bank", "class": "memory",
                           "attrs": {"size_kb": size_kb, "word_width_bits": WIDTH_BITS}}]}
    binary = CactiEvaluator()._ensure_cacti_binary()
    native = run_cacti(architecture_ir_to_sram_spec(arch), technology_um=0.032,
                       cacti_path=str(binary))
    efficiency = measure_area_efficiency(arch, 0.032, cacti_path=str(binary))
    bits = int(size_kb * 1024 * 8)
    one_bank, note = scale_area_mm2(native.height_mm * native.width_mm, from_nm=32, to_nm=7,
                                    bits=bits, array_efficiency=efficiency)
    return one_bank * BANKS, note


