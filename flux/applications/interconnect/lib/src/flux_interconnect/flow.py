def critical_arity(spec: dict | None) -> int:
    """The widest selector in a fabric — the one that sets its clock (docs/decisions.md D339).

    A repair attacks the critical path, so this is the thing that decides what a repair IS. Two
    fabrics with the same widest selector are one repair problem however differently they are
    spelled.
    """
    from flux_interconnect import build
    from flux_interconnect.fabric import canonical_stages

    if not isinstance(spec, dict):
        return 0
    try:
        return max(int(s.get("in", 1)) for s in canonical_stages(build(spec)))
    except Exception:  # noqa: BLE001 — a fabric we cannot build has no critical path to name
        return 0


def near_misses(db: str, *, floor: float | None = None, band: float = 0.12,
                distinct: bool = False) -> list[dict]:
    """Fabrics that got all the way to real tools, carry every client, and JUST miss timing.

    These are the search's most informative failures and it currently throws all of them away.
    A design measured at 595 MHz against a 600 MHz floor is not a bad idea; it is a good idea
    with one stage too slow, and the run already knows which arity is on its critical path
    because the evaluator recorded the per-block delays. Seventeen such fabrics sit in this
    store, one of them five megahertz short (D317).

    Returned worst-first-but-closest-first: the nearest miss is the most likely to be fixable.
    """
    import sqlite3

    # Resolved HERE, not in the signature. A default argument binds at import, so once the
    # problem can be authored at run time (D333) a captured `TARGET_MHZ` would keep screening
    # against 600 MHz in a study the user asked to run at 1 GHz.
    floor = TARGET_MHZ if floor is None else floor
    out: dict[str, dict] = {}
    try:
        con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    except sqlite3.Error:
        return []
    try:
        rows = con.execute(
            "select t.candidate_json, r.result_json from trials t "
            "join results r on t.result_id = r.id where t.phase = 'escalate'").fetchall()
    except sqlite3.Error:
        return []
    finally:
        con.close()
    for candidate_json, result_json in rows:
        try:
            candidate, result = json.loads(candidate_json), json.loads(result_json)
        except ValueError:
            continue
        metrics = result.get("metrics", {})

        def value(key, _m=metrics):
            return (_m.get(key) or {}).get("value")

        fmax = value("fmax_mhz")
        label, variant = candidate.get("label"), candidate.get("variant")
        if not (fmax and label and variant):
            continue
        if value("max_throughput_words_per_cycle") != CLIENTS:
            continue          # a narrow waist is a different problem, not a timing near-miss
        if not floor * (1 - band) <= fmax < floor:
            continue
        if label not in out or fmax > out[label]["fmax_mhz"]:
            out[label] = {"label": label, "variant": variant, "fmax_mhz": fmax,
                          "blocks": (result.get("provenance", {}).get("inputs", {})
                                     .get("blocks", ""))}
    ranked = sorted(out.values(), key=lambda r: -r["fmax_mhz"])
    if not distinct:
        return ranked
    # ONE per critical path. Six of eight near-misses in this store share a 28:1 selector and four
    # share 564 MHz; offering them separately had the model repair the same bottleneck four times
    # in one run, at about 160 seconds a call, all four choosing the same 14:1 fix. Closest miss
    # per distinct arity, because the nearest one is the likeliest to be fixable and whatever
    # fixes it is the same change the others need.
    seen: set[int] = set()
    unique = []
    for row in ranked:
        arity = critical_arity(row["variant"])
        if arity in seen:
            continue
        seen.add(arity)
        unique.append(row)
    return unique


