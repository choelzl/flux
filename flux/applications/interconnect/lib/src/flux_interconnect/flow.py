def calibration_bucket(spec: dict | None) -> str | None:
    """Which residual sub-pool a fabric belongs to (docs/decisions.md D318).

    DEPTH, because that is what the evidence supports and nothing more. Over 45 fabrics placed
    whole against their composed estimates, the optimism is not one number: depth-2 designs read
    0.85x and depth-1 read 0.75x, and pooling them gives a correction whose spread (0.59-0.96) is
    nearly as large as the correction itself. Splitting by depth cut leave-one-out mean error from
    62 MHz to 51.

    Depth and not arity, family, or link count, although all three were available: with 45 points
    a finer split makes each pool too thin to clear the trust threshold, and a correction fitted
    on three residuals is the failure D101 already recorded. Depth is also the mechanism — each
    rank is another selector delay in series — rather than a variable that happened to correlate.
    """
    if not isinstance(spec, dict):
        return None
    stages = spec.get("stages")
    depth = len(stages) if isinstance(stages, list) and stages else 1
    return f"depth{min(depth, 4)}"          # 4+ is one pool: only one fabric here is deeper


def corrected_fmax(db: str, spec: dict | None, composed_mhz: float) -> tuple[float, str]:
    """Apply the measured composed-to-placed correction, conditioned on depth (D318).

    THE NUMBER THIS FIXES. `fmax_mhz` on the frontier is the COMPOSED estimate: each selector
    arity placed alone and summed, with no wire between switches priced. Placing 45 of this
    store's fabrics whole showed it reads a median 0.80x optimistic, and 25 of those 45 did not
    meet the 600 MHz constraint they were reported as meeting (D316). That number decides which
    fabrics qualify and therefore which get real tool time, so leaving it uncorrected does not
    merely misreport the answer — it picks the wrong finalists to check.

    Conditioned on depth rather than pooled: depth-2 fabrics read +0.19 and depth-1 +0.35, and the
    pooled +0.29 is wrong for both, in opposite directions. Falls back to the pooled pool when a
    depth has too few records, and returns the estimate untouched when there is no calibration at
    all — an uncorrected number is honest; an invented correction is not.

    Returns `(mhz, note)` so a caller can SHOW the correction rather than silently applying it.
    """
    from flux_evaluator_interconnect_phys.adapter import EVALUATOR_ID

    bucket = calibration_bucket(spec)
    try:
        from flux_calibration import CalibrationStore

        with CalibrationStore(_calibration_path(db)) as cal:
            stats = cal.residual_stats(EVALUATOR_ID, "fmax_mhz", bucket=bucket) if bucket else None
            source = bucket or ""
            if stats is None or stats.n < _MIN_BUCKET_RECORDS:
                pooled = cal.residual_stats(EVALUATOR_ID, "fmax_mhz")
                if pooled is not None and (stats is None or pooled.n > stats.n):
                    stats, source = pooled, "pooled"
    except (OSError, ValueError, ImportError):
        # NARROW deliberately. A blanket `except Exception` here swallowed a TypeError from
        # calling `residual_stats` with an argument it did not yet accept, so the correction
        # silently never applied and looked exactly like a store with no calibration in it.
        return composed_mhz, ""
    if stats is None or stats.n == 0:
        return composed_mhz, ""
    denominator = 1.0 + stats.mean_relative_residual
    if denominator <= 0:
        return composed_mhz, ""
    return composed_mhz / denominator, f"{source} n={stats.n}"


def dead_ports(spec: dict | None) -> tuple[int, int]:
    """(unused client inputs, unused bank outputs) at the fabric's boundary.

    A first stage admitting more ports than there are clients, or a last stage driving more than
    there are banks, carries wires to nothing. It is NOT refused, and the measurement says why:
    717 of 1,184 feasible fabrics here have at least one dead port, and the cheapest routable
    fabric in the whole space has four dead inputs (81,920 mux bits against 86,016 for the best
    exact fit). A switch count that divides evenly downstream can more than pay for a few unused
    ports upstream, so banning them would delete the cheapest design available.

    What was wrong was that the waste was invisible. Synthesis optimises dead ports away, so three
    fabrics differing only in how many they carried all placed at ~0.0155 mm2 and took three of
    five finalist placements between them. The screen prices the waste (8-14% more mux bits) and
    silicon does not, which is exactly the kind of disagreement a reader has to be shown rather
    than left to infer.
    """
    from flux_interconnect import build
    from flux_interconnect.fabric import canonical_stages

    if not isinstance(spec, dict):
        return 0, 0
    try:
        stages = canonical_stages(build(spec))
    except Exception:  # noqa: BLE001 — a fabric we cannot build has no boundary to measure
        return 0, 0
    first, last = stages[0], stages[-1]
    return (max(0, first["switches"] * first["in"] - CLIENTS),
            max(0, last["switches"] * last["out"] - BANKS))


def dead_note(spec: dict | None) -> str:
    """A short phrase naming a fabric's boundary waste, or "" when it has none.

    Attached wherever a fabric is NAMED as an answer, not only where it is tabulated. A reader who
    sees "SMALLEST that meets timing: xbar_staged-8x4x4-4x8x8" and acts on it should not have to
    cross-reference a column to learn that four of its client ports go nowhere (D326).
    """
    din, dout = dead_ports(spec)
    if not (din or dout):
        return ""
    parts = []
    if din:
        parts.append(f"{din} unused client port(s)")
    if dout:
        parts.append(f"{dout} unused bank port(s)")
    return f" [carries {' and '.join(parts)}]"


def choose_finalists(by_area: list[tuple[str, dict]], count: int,
                     shape_of, log=print) -> list[tuple[str, dict]]:
    """Pick which fabrics earn a whole-fabric placement (docs/decisions.md D327).

    MODULE LEVEL, not nested in `main`, so it can be tested. Every defect this demo shipped in a
    single session lived in a nested function nothing could import, and the tests were green each
    time (D317, D321, D323).

    Two rules, in two passes:

      1. Not the same silicon twice. `shape_of` collapses labels that name one fabric — a radix-4
         hybrid over 28 clients IS 7x(4x4), and the shortlist used to place it under both names.
      2. Not the same POINT twice. Three structurally distinct fabrics took three of five
         placements and landed within 0.0002 mm2 and 0.2 words/cycle of each other. The screen had
         separated them by 8-14% on mux bits; the placer put them within 1.3%. Two designs the
         screen already places this close will not distinguish themselves by being placed, and a
         placement is minutes.

    The second pass drops rule 2 to fill any shortfall, because a front with three distinct points
    should still spend five placements if five were budgeted — a diversity rule that quietly buys
    fewer measurements is a worse trade than the clustering it prevents.
    """
    finalists: list[tuple[str, dict]] = []
    shapes: set = set()
    points: list[tuple[float, float]] = []
    taken: set[str] = set()

    def near_existing(metrics: dict) -> bool:
        for area, served in points:
            if (abs(metrics["area_mm2"] - area) <= _SAME_POINT_AREA * max(area, 1e-9)
                    and abs(metrics["served"] - served)
                    <= _SAME_POINT_SERVED * max(served, 1e-9)):
                return True
        return False

    for require_diversity in (True, False):
        for label, metrics in by_area:
            if len(finalists) >= count:
                break
            if label in taken:
                continue
            shape = shape_of(label)
            if shape is not None and shape in shapes:
                if require_diversity:
                    log(f"    (skipping {label}: same fabric as one already shortlisted)")
                continue
            if require_diversity and near_existing(metrics):
                log(f"    (skipping {label}: the screen puts it on the same point as one "
                    "already shortlisted)")
                continue
            shapes.add(shape)
            points.append((metrics["area_mm2"], metrics["served"]))
            taken.add(label)
            finalists.append((label, metrics))
        if len(finalists) >= count:
            break
    return finalists


def learn_from_placement(db: str, label: str, composed: dict, placed: dict,
                         spec: dict | None = None) -> str:
    """Turn one whole-fabric placement into something the SCREEN can use (D305).

    A placement already produced the pair that matters: what composition predicted and what
    silicon did. Printed and discarded, it improves one row. Recorded as a residual, it corrects
    every screening estimate that follows, because the composed rung's error is systematic — it
    prices gates and none of the wire between them, so it runs optimistic on frequency by 100 to
    200 MHz (D280) and the 600 MHz constraint is applied to those optimistic numbers.

    Also written as a FACT, so the lessons brief can tell the orchestrator which fabrics have
    settled frequencies and by how much the screen missed. Deciding what to measure next is
    guesswork without it.
    """
    from flux_calibration import CalibrationStore
    from flux_evaluator_interconnect_phys.adapter import EVALUATOR_ID
    from flux_knowledge_mining import Fact, FactStore, fact_store_path

    note = ""
    predicted, reference = composed.get("fmax_mhz"), placed.get("fmax_mhz")
    if not predicted or not reference:
        return note
    error = (predicted - reference) / reference
    try:
        with CalibrationStore(_calibration_path(db)) as cal:
            cal.add_record(
                workload_hash=f"interconnect/{CLIENTS}c-{BANKS}b-{WIDTH_BITS}b",
                arch_hash=label, evaluator=EVALUATOR_ID, metric="fmax_mhz",
                predicted_value=float(predicted), reference_value=float(reference),
                reference_source="whole-fabric placement on the vendored core",
                bucket=calibration_bucket(spec))
                # NO caveat, deliberately. `records_for` excludes caveated records from residual
                # statistics by default, so a caveat here would store every residual and use none
                # of them — the flywheel would spin without turning anything. The caveat field is
                # for comparisons that are not clean; composed-estimate against placed-silicon is
                # precisely the comparison being calibrated, and its nuance belongs in
                # `reference_source`, which names exactly what the reference was.
        note = (f"composed fmax read {error:+.0%} against placed silicon for {label} "
                f"({predicted:.0f} vs {reference:.0f} MHz)")
        with FactStore(fact_store_path(db)) as facts:
            facts.put_facts([Fact(
                kind="estimator_bias", statement=note,
                evidence={"label": label, "composed_fmax_mhz": predicted,
                          "placed_fmax_mhz": reference, "relative_error": error},
                scope=f"one fabric of this study, placed whole on the vendored core",
                not_established="that the same error applies to fabrics of other shapes or depths",
                pointers={"metric": "fmax_mhz", "evaluator": EVALUATOR_ID})])
    except Exception as exc:  # noqa: BLE001 — learning is optional, the measurement is not
        print(f"    (residual not recorded: {type(exc).__name__}: {str(exc)[:50]})")
    return note


def variants_round(db: str, round_no: object, variants: list[dict], label: str) -> dict:
    """A campaign whose whole space is a named list of fabrics — the neighbours of an incumbent.

    The same machinery as an enumerated round: each variant is built, routed, screened, and
    escalated if it earns it. What differs is only where the candidates came from.
    """
    from flux_chia_nodes import (
        flux_campaign_frontier,
        flux_campaign_start,
        flux_campaign_status,
        flux_campaign_step,
    )

    doc = objective_document(round_no=round_no, variants=variants,
                             budget=len(variants) + ESCALATION_HEADROOM)
    started = flux_campaign_start(doc, db)
    print(f"\n=== round {round_no}: {len(variants)} neighbours of {label}")
    report = flux_campaign_step(db, started["campaign_id"], max_trials=10_000,
                                escalation_parallelism=ESCALATION_WORKERS,
                                calibration_db_path=_calibration_path(db))
    status = flux_campaign_status(db, started["campaign_id"])
    frontier = flux_campaign_frontier(db, started["campaign_id"], include_contenders=True)
    print(f"    {report['status']}: {status['trial_counts']}, "
          f"{len(frontier['contenders'])} contenders escalated")
    return {"campaign_id": started["campaign_id"], "report": report, "space": len(variants)}


def _structural_key(label: str, _cache: dict = {}) -> tuple | None:
    """What a fabric IS, rather than how it was named: its blocks, depth and routing policy.

    Two labels with the same key are the same silicon and must not be measured twice.
    """
    if label in _cache:
        return _cache[label]
    variant = _variant_lookup.get(label)
    if variant is None:
        return None
    try:
        from flux_interconnect import build

        from flux_interconnect.perturb import structural_key

        key = structural_key(variant)
    except Exception:  # noqa: BLE001
        key = None
    _cache[label] = key
    return key


