def frontier_digest(db: str, limit: int = 6) -> str:
    """What the study actually HAS, for the orchestrator's prompt (docs/decisions.md D330).

    The shared renderer sorts by the first metric and takes the top few, which for this
    application meant the six cheapest fabrics — and the cheapest fabrics were the unroutable
    ones, because a fabric missing connections is missing the muxes that would have cost area.
    The model opened every decision looking at a list led by three designs that cannot deliver a
    word, six rows out of fifty-seven.

    So this filters and then shows BOTH ENDS. A search told only about the cheapest corner has no
    way to see the trade-off it is meant to be exploring, and the answer to "what should I do
    next" depends on the shape of the front rather than on its floor.
    """
    from flux_evaluator_interconnect_phys.adapter import EVALUATOR_ID
    # Imported HERE. `main` imports it into its own scope, so a module-level function that
    # assumed it was global raised NameError — which a blanket `except Exception` then reported
    # as "(nothing measured yet)" against a store holding fifty-seven measured fabrics. The same
    # shape as D322: a defensive catch turning a wiring mistake into a plausible empty answer.
    from flux_store import CampaignStore

    try:
        measured, _refused, _stale = measured_results(
            CampaignStore(db), EVALUATOR_ID,
            {"area_mm2": "area_mm2", "fmax_mhz": "fmax_mhz",
             "served": "throughput_words_per_cycle",
             "max_served": "max_throughput_words_per_cycle"})
    except (OSError, ValueError, KeyError):
        return "(nothing measured yet)"

    from flux_evaluator_interconnect_struct.adapter import _unroutable_reason
    from flux_interconnect import build

    rows = []
    for label, row in measured.items():
        spec = (row.get("_candidate") or {}).get("variant")
        if spec is None:
            continue
        try:
            if _unroutable_reason(build(spec)):
                continue          # cannot deliver to every bank: not part of the frontier (D319)
        except (ValueError, KeyError, TypeError):
            continue              # a spec we cannot rebuild is not evidence either way
        if (row.get("max_served") or 0) < CLIENTS:
            continue
        corrected, _note = corrected_fmax(db, spec, float(row["fmax_mhz"]))
        rows.append((label, row, corrected, spec))
    if not rows:
        return "(nothing measured yet)"

    passing = [r for r in rows if r[2] >= TARGET_MHZ]
    if not passing:
        return (f"({len(rows)} fabrics measured, none clears {TARGET_MHZ:.0f} MHz once the "
                "measured composed-to-placed correction is applied)")

    by_area = sorted(passing, key=lambda r: r[1]["area_mm2"])
    by_served = sorted(passing, key=lambda r: -r[1]["served"])
    # Both ends and the span between them, deduplicated: the smallest, the fastest, and whatever
    # else fits. `fmax` is the CORRECTED number, because that is the one the constraint is applied
    # to and showing the optimistic one invites the model to trust a fabric that will not close.
    # One row per FABRIC, not per label. `hybrid-radixradix4-xbarswitches4` and
    # `xbar_staged-7x4x4-4x7x8-first` ARE `xbar_staged-7x4x4-4x7x8`, and three of six rows in this
    # digest were the same silicon under three names — half the model's view of the study spent
    # restating one design (D311 collapsed these everywhere else; the prompt was missed).
    picked: list = []
    seen_shapes: set = set()
    for row in by_area[:1] + by_served[:1] + by_area[1:]:
        # From the SPEC in hand, not `_structural_key(label)`: that reads `_variant_lookup`, which
        # `main` fills only when it builds the results table — after the search. During a run it
        # was empty, every key came back None, and the dedup silently did nothing.
        shape = _structural_key_of_spec(row[3])
        if row[0] in {p[0] for p in picked} or (shape is not None and shape in seen_shapes):
            continue
        seen_shapes.add(shape)
        picked.append(row)
        if len(picked) >= limit:
            break
    lines = [f"  {len(passing)} of {len(rows)} measured fabrics clear "
             f"{TARGET_MHZ:.0f} MHz and carry all {CLIENTS} clients:"]
    for label, row, corrected, _spec in picked:
        lines.append(f"  {label[:38]:<40}area_mm2={row['area_mm2']:.4g}  "
                     f"fmax_mhz={corrected:.0f}  served={row['served']:.3g}")
    return "\n".join(lines)


def ceiling_for(variant: dict | None) -> int:
    """Transfers the fabric can carry at once: a count fixed by its narrowest point. Structural,
    so it is recomputed from the candidate rather than stored."""
    if not variant:
        return 0
    from flux_interconnect import build

    try:
        return build(variant).max_served_per_cycle()
    except Exception:  # noqa: BLE001 — a capacity we cannot derive is reported as unknown
        return 0


def measure_throughput_cached(topo) -> float:
    """Words per cycle from the RTL, memoised by fabric — the decision rung re-places a fabric
    but its throughput does not change with the switch implementation (D279 measured the two
    backends agreeing to within 0.02), so it is measured once."""
    from flux_interconnect.fabric import measure_throughput

    # The shared identity, which INCLUDES routing where routing matters. This cache keyed by
    # (kind, blocks, stages) alone, so a fabric and its `-first` variant shared an entry and the
    # second silently received the first's number — 13.55 returned for a fabric that measures
    # 8.90, a 52% error delivered as a cache hit (D311).
    from flux_interconnect.perturb import structural_key_of

    key = structural_key_of(topo)
    if key not in _THROUGHPUT_CACHE:
        _THROUGHPUT_CACHE[key] = measure_throughput(topo, cycles=20000)[
            "measured_words_per_cycle"]
    return _THROUGHPUT_CACHE[key]


