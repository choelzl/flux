def placed_whole(db: str, spec: dict, *, timeout_s: int = 5400) -> dict:
    """Place a fabric whole, or return the placement already on disk (docs/decisions.md D340).

    THE COST THIS AVOIDS. A whole-fabric placement is real Yosys and OpenROAD on the complete
    design — about five minutes each. Nothing cached them, so one run placed
    `xbar_staged-7x4x4-4x7x8` for the `measure` action and then placed the SAME fabric again
    minutes later as a decision-rung finalist, and every subsequent run re-placed all five
    finalists from scratch. The decision rung is five placements; on a warm store almost none of
    them are new.

    KEYED BY (toolchain, fabric). The fabric part is `structural_key`, the one definition of
    identity (D311), so two labels naming one design share an entry. The toolchain part is the
    fingerprint from D316 — a placement is only valid for the binaries that produced it, and this
    is the first thing in the repo that can ACT on that rather than warn about it: bump OpenROAD
    and the cached numbers stop being served instead of being served with a caveat.

    A cache that cannot be read is a cache miss, never an error: this is an optimisation, and a
    corrupt or unreadable sidecar must not stop a study.
    """
    from flux_evaluator_abi import toolchain_fingerprint
    from flux_interconnect import build
    from flux_interconnect.fabric import measure_whole_fabric
    from flux_interconnect.perturb import structural_key_of
    from flux_cache import MeasurementCache

    topo = build(spec)
    try:
        identity = str(structural_key_of(topo))
    except Exception:  # noqa: BLE001 — a fabric we cannot key is simply not cached
        return measure_whole_fabric(topo, switch="vendored", timeout_s=timeout_s)
    cache = MeasurementCache(db, toolchain_fingerprint())
    return cache.get_or_measure(
        identity, lambda: measure_whole_fabric(topo, switch="vendored", timeout_s=timeout_s))


def worth_placing(db: str, *, limit: int = 5) -> list[str]:
    """Fabrics that would repay a whole-fabric placement, cheapest first (docs/decisions.md D341).

    `measure` was the last action declaring no variants, and the cost showed: over two runs the
    model asked to place `xbar_staged-7x4x4-4x7x8` four times after it had already been placed,
    paying a model call each time to be told so. Its legal set is every fabric in a 3,500-row
    store, which is why it was left alone — but the set worth OFFERING was never that. It is the
    handful the decision would actually turn on.

    Three filters, each of which the run already computes for other reasons: the fabric must
    route (D319), it must clear the constraint once the measured composed-to-placed correction is
    applied (D322), and it must not already be in the placement cache (D340). That last one is
    what makes this possible at all — before the cache there was no cheap way to ask what had
    been placed.
    """
    from flux_evaluator_abi import toolchain_fingerprint
    from flux_evaluator_interconnect_phys.adapter import EVALUATOR_ID
    from flux_evaluator_interconnect_struct.adapter import _unroutable_reason
    from flux_interconnect import build
    from flux_interconnect.perturb import structural_key_of
    from flux_store import CampaignStore
    from flux_cache import MeasurementCache

    try:
        measured, _refused, _stale = measured_results(
            CampaignStore(db), EVALUATOR_ID,
            {"area_mm2": "area_mm2", "fmax_mhz": "fmax_mhz",
             "max_served": "max_throughput_words_per_cycle"})
    except (OSError, ValueError, KeyError):
        return []

    # ASK THE CACHE, rather than re-deriving its key format here. This built the key itself and
    # the two spellings agreed only by luck — which is precisely how the dedup signature and the
    # stored one drifted apart in D302, and it stopped catching anything at all.
    cache = MeasurementCache(db, toolchain_fingerprint())

    rows: list[tuple[float, str]] = []
    offered: set[str] = set()
    for label, row in sorted(measured.items()):
        spec = (row.get("_candidate") or {}).get("variant")
        if spec is None or (row.get("max_served") or 0) < CLIENTS:
            continue
        try:
            topo = build(spec)
            if _unroutable_reason(topo):
                continue
            identity = str(structural_key_of(topo))
        except Exception:  # noqa: BLE001 — a fabric we cannot rebuild is not worth offering
            continue
        if cache.holds(identity) or identity in offered:
            # `key in offered` is the fourth appearance of one pattern in this file: the top three
            # candidates here were `hybrid-radixradix4-xbarswitches4`,
            # `xbar_staged-7x4x4-4x7x8` and `...-first`, which are one fabric under three names.
            # Offering a placement of the same silicon three times is what D311, D327 and D339
            # each fixed somewhere else.
            continue
        corrected, _note = corrected_fmax(db, spec, float(row["fmax_mhz"]))
        if corrected < TARGET_MHZ:
            continue
        offered.add(identity)
        rows.append((row["area_mm2"], label))
    return [label for _area, label in sorted(rows)[:limit]]


