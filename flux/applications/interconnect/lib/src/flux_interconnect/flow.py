def _variant_named(ctx: "StudyContext", label: str) -> dict | None:
    for row in CampaignStore(ctx.args.db).list_campaigns():
        for trial in CampaignStore(ctx.args.db).trials(row["campaign_id"]):
            if trial.candidate.get("label") == label and trial.candidate.get("variant"):
                return trial.candidate["variant"]
    return None


def _measure(ctx: "StudyContext", params: dict) -> Outcome:
    from flux_evaluator_interconnect_phys.adapter import EVALUATOR_ID

    """Place ONE named fabric for real, because the orchestrator asked.

    The screen composes per-arity block measurements and prices no wire between switches, so
    it runs optimistic on frequency by 100-200 MHz (D280). Until now only the final decision
    rung could settle that, at the very end. This lets the search spend a real placement
    mid-flight on a design it is unsure about, which is what a person would do.
    """
    from flux_interconnect import build
    from flux_interconnect.fabric import measure_whole_fabric

    label = str(params["label"])
    variant = _variant_named(ctx, label)
    if variant is None:
        return Outcome(progressed=False, detail=f"no fabric named {label} in this store")
    try:
        with _phase("on-demand placement (whole fabric)"):
            whole = placed_whole(ctx.args.db, variant, timeout_s=5400)
    except Exception as exc:  # noqa: BLE001 — a failed placement is data, not a crash
        return Outcome(progressed=False,
                       detail=f"{label}: placement failed ({str(exc)[:60]})")
    detail = (f"{label} PLACED WHOLE: {whole['area_mm2']:.4f} mm2 at "
              f"{whole['fmax_mhz']:.0f} MHz (measured, not composed)")
    print(f"    {detail}", flush=True)
    # Every placement teaches the screen, not just this row (D305). The composed estimate
    # comes from the store rather than a local table, because this runs mid-search and the
    # ctx.results table is not assembled until the end.
    composed_rows, _, _ = measured_results(
        CampaignStore(ctx.args.db), EVALUATOR_ID, {"fmax_mhz": "fmax_mhz"})
    learned = learn_from_placement(ctx.args.db, label, composed_rows.get(label, {}), whole,
                                   spec=variant)
    if learned:
        print(f"    learned: {learned}", flush=True)
        detail += f"; {learned}"
    # No new fabric was tried, and the step was still worth taking.
    return Outcome(progressed=True, detail=detail)


def _population(ctx: "StudyContext") -> list[dict]:
    """The designs a walk may start from: everything this run has actually tried.

    Seeded from the enumerated space only when the store is empty, because the point of
    annealing is to exploit what the study has learned. Starting every chain from a fresh
    enumeration each time would make the search memoryless.
    """
    from flux_interconnect.anneal import objective, screen

    specs, seen = [], set()
    store = CampaignStore(ctx.args.db)
    for row in store.list_campaigns():
        for trial in store.trials(row["campaign_id"]):
            variant = trial.candidate.get("variant")
            if not variant:
                continue
            marker = json.dumps(variant, sort_keys=True)
            if marker not in seen:
                seen.add(marker)
                specs.append(variant)
    if not specs:
        from flux_interconnect.topology import enumerate_space

        specs = enumerate_space(CLIENTS, BANKS, WIDTH_BITS, max_stages=3,
                                max_candidates=4000, breadth="wide")
    out = []
    for spec in specs:
        try:
            cost = objective(screen(spec), clients=CLIENTS)
        except Exception:  # noqa: BLE001 -- a design that will not screen is not a start
            continue
        if cost is not None:
            out.append({"spec": spec, "cost": cost})
    return out


def _anneal(ctx: "StudyContext", params: dict) -> Outcome:
    """Monte-Carlo: many annealing chains over the screen, then place what they surface.

    The screen runs at ~30,000 designs/second and one real placement costs minutes, so the
    cheap thing is spent without counting and the expensive thing only on what survives.

    It does NOT beat enumeration at the extremes of any single objective; it widens the
    trade-off surface with structures no enumeration lists (D313).
    """
    from flux_interconnect.anneal import ensemble

    # `from` starts every chain at one named design instead of sampling the population.
    # This is what `perturb` used to be, done properly: a chain that WALKS from the incumbent
    # rather than looking at its seven neighbours once and stopping (D313/D317).
    start = str(params.get("from") or "")
    if start:
        variant = _variant_named(ctx, start)
        if variant is None:
            return Outcome(progressed=False, detail=f"no fabric named {start} to anneal from")
        from flux_interconnect.anneal import objective as _obj, screen as _scr

        cost = _obj(_scr(variant), clients=CLIENTS)
        if cost is None:
            return Outcome(progressed=False,
                           detail=f"{start} cannot carry every client, so there is nowhere "
                                  "feasible to walk from")
        population = [{"spec": variant, "cost": cost}] * 2
    else:
        population = _population(ctx)
    if len(population) < 2:
        return Outcome(progressed=False, detail="nothing feasible to anneal from yet")
    chains, steps = int(params["chains"]), int(params["steps"])
    seed, place = int(params["seed"]), int(params["place"])
    with _phase("monte-carlo: annealing over the screen"):
        result = ensemble(population, clients=CLIENTS, chains=chains, steps=steps, seed=seed,
                          recombine=max(20, chains * 12))
    where = f" from {start}" if start else ""
    print(f"    {len(result.steps):,} proposals{where} from {len(population):,} known "
          f"designs, {result.acceptance_rate:.0%} accepted, {result.kicks} kicks out of a "
          f"basin, Pareto archive {len(result.archive)}", flush=True)
    picked = result.top(place)
    if not picked:
        return Outcome(progressed=False, detail="the walk found nothing feasible")
    before = campaign_tally(ctx.args.db)["attempted"]
    with _phase("round: annealed candidates (total)"):
        ctx.results.append(variants_round(ctx.args.db, f"a{len(ctx.results) + 1}", picked,
                                      f"monte-carlo ({chains}x{steps}, seed {seed}{where})"))
    gained = campaign_tally(ctx.args.db)["attempted"] - before
    return Outcome(gained=gained,
                   detail=f"{len(result.steps):,} screened proposals -> {len(picked)} placed")


def _repair(ctx: "StudyContext", params: dict) -> Outcome:
    """The FAIL EDGE: hand a measured failure back to the model and try the fix it picks.

    The model CHOOSES from constructed candidates rather than authoring a spec. Free-form
    authoring was tried first and failed on both attempts it got — "final stage drives 16
    outputs < 32 banks", "stage 1 emits 96 links but stage 2 takes 48". Chaining a staged
    fabric is an invariant a language model does not hold while writing JSON, and it is
    exactly what `mutate` enforces by construction. So the model does the part it is good at,
    judging which change attacks the critical path, and never the part it is bad at.

    Every candidate is built, routable and carries all clients before the model sees it, so a
    bad choice costs one placement rather than producing garbage.
    """
    from flux_interconnect.anneal import objective, screen
    from flux_interconnect.perturb import mutate

    candidates = near_misses(ctx.args.db)
    if not candidates:
        return Outcome(progressed=False, detail="no near-miss failures to repair")
    wanted = str(params.get("label") or "")
    target = next((c for c in candidates if c["label"] == wanted), None) if wanted \
        else candidates[0]
    if target is None:
        return Outcome(progressed=False, detail=f"{wanted} is not a near-miss in this store")
    if ctx.ask is None:
        return Outcome(progressed=False, detail="no local model to repair with")

    def widest(spec: dict) -> int:
        stages = spec.get("stages") or []
        return max([int(s.get("in", 1)) for s in stages],
                   default=int(spec.get("radix", 1)))

    base_widest = widest(target["variant"])
    options: list[dict] = []
    seen = {_structural_key_of_spec(target["variant"])}
    for radius in ("small", "large"):
        for spec in mutate(target["variant"], radius=radius, limit=32):
            key = _structural_key_of_spec(spec)
            if key in seen:
                continue
            metrics = screen(spec)
            if objective(metrics, clients=CLIENTS) is None:
                continue          # unroutable or too narrow: not a repair (D319)
            seen.add(key)
            options.append({"spec": spec, "widest": widest(spec),
                            "mux_bits": metrics["mux_bits"]})
    # Narrowest-selector first: the arity that sets the clock is what a repair must attack,
    # so the list the model reads is ordered by the thing it is being asked to reason about.
    options.sort(key=lambda o: (o["widest"], o["mux_bits"]))
    options = options[:12]
    if not options:
        return Outcome(progressed=False,
                       detail=f"{target['label']} has no buildable, routable repair")

    listing = "\n".join(
        f"  {i}. widest selector {o['widest']}:1 (was {base_widest}:1), "
        f"{o['mux_bits']:,.0f} mux bits — {json.dumps(o['spec'].get('stages'))}"
        for i, o in enumerate(options, 1))
    print(f"\n=== repairing {target['label']} ({target['fmax_mhz']:.0f} MHz, needs "
          f"{TARGET_MHZ:.0f}): {len(options)} constructed candidates", flush=True)
    with _phase("llm: repairing a failed design"):
        try:
            raw = ctx.ask(_REPAIR_PROMPT.format(
                label=target["label"], fmax=target["fmax_mhz"], target=TARGET_MHZ,
                short=TARGET_MHZ - target["fmax_mhz"], clients=CLIENTS,
                blocks=target["blocks"] or "(not recorded)", options=listing))
        except Exception as exc:  # noqa: BLE001 — a dead model costs a step, not the run
            return Outcome(progressed=False,
                           detail=f"repair call failed ({type(exc).__name__})")
    from flux_llm import strip_markdown_fence

    try:
        choice = json.loads(strip_markdown_fence(raw).strip())
        picked = options[int(choice["choice"]) - 1]
    except (ValueError, KeyError, TypeError, IndexError):
        return Outcome(progressed=False, detail=f"unusable repair choice: {raw[:60]}")
    print(f"    chose #{choice['choice']}: widest {picked['widest']}:1 — "
          f"{str(choice.get('because', ''))[:80]}", flush=True)

    before = campaign_tally(ctx.args.db)["attempted"]
    with _phase("round: repaired candidate (total)"):
        ctx.results.append(variants_round(ctx.args.db, f"r{len(ctx.results) + 1}", [picked["spec"]],
                                      f"repair of {target['label']}"))
    gained = campaign_tally(ctx.args.db)["attempted"] - before
    return Outcome(gained=gained,
                   detail=f"repaired {target['label']}: {base_widest}:1 -> "
                          f"{picked['widest']}:1 widest selector")


def _valid_repair(ctx: "StudyContext", params: dict) -> dict | None:
    """Refuse a label that is not a near-miss, rather than spending a step to decline it.

    D328 gave `repair` declared variants so the menu lists the fabrics that CAN be repaired,
    and the very next run picked one that was not among them: the menu said
    `label: one of <six near-misses>` and the model asked to repair
    `xbar_staged-7x4x4-7x4x4-14x2x3`, which meets timing. Declaring legal values informs the
    prompt; it does not constrain the reply, and nothing was checking.

    An unusable choice costs a re-plan here instead of a step and a model call, which is the
    difference between the loop correcting the model and the loop obeying it.
    """
    label = str(params.get("label", ""))
    if not label:
        return {"label": ""}          # empty means "the closest miss", which is always legal
    # Read fresh rather than trusting the menu's snapshot: a fabric repaired earlier in this
    # same run is no longer a near-miss, and the declared list was built before any step ran.
    if label not in {row["label"] for row in near_misses(ctx.args.db)}:
        return None
    return {"label": label}


def _valid_anneal(params: dict) -> dict | None:
    try:
        out = {"from": str(params.get("from", "")),
               "chains": max(1, min(64, int(params.get("chains", 16)))),
               "steps": max(1, min(4000, int(params.get("steps", 1200)))),
               "seed": int(params.get("seed", 0)),
               # Capped hard: each of these is real Yosys and OpenROAD, and a model that
               # asks for forty placements has not understood what it is spending.
               "place": max(1, min(8, int(params.get("place", 4))))}
    except (TypeError, ValueError):
        return None
    return out


