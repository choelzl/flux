        print("   Whether that matters depends on how far the tools moved; this repo has not "
              "yet seen a bump change a composed number by more than about a percent.")
        print(f"   Re-measure, or start a fresh store. Delete {baseline.path.name} to accept the "
              "new toolchain as this store's baseline.\n")
