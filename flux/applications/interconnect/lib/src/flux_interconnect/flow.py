def record_conclusions(db: str, ask, *, limit: int = 3) -> list[str]:
    """Ask the model what this run's measurements mean, and store what survives validation.

    Returns one display line per stored conclusion, empty when none were drawn. Never raises: a
    lesson is the most optional thing in the run, and losing it must not cost the results that
    were actually measured.
    """
    try:
        from flux_chia_nodes import flux_mine_knowledge
        from flux_knowledge_mining import (
            FactStore,
            balanced_evidence,
            draft_conclusions,
            store_conclusions,
        )

        facts = flux_mine_knowledge(campaign_db_paths=[db]).get("facts", [])
        if not facts:
            return []
        # BALANCED, not refusals-first. Ranking refusals ahead of everything and truncating gave
        # the model eighteen failures out of a 506-fact store and not one success, and it drew the
        # obvious conclusion from them: that 28 words/cycle was "unreachable", while the same
        # run's results table listed thirty-one fabrics reaching it (D314). Every kind of fact
        # present now contributes before any kind contributes twice.
        ranked = balanced_evidence(facts, limit=18)
        # Its OWN short-lived model, not the orchestrator's. The shared default allows an hour
        # per call, which is right for a proposal the run depends on and wrong for a lesson it
        # does not: the results are already printed by this point, and nothing below needs this
        # to succeed. A lesson that costs an hour of a user's evening is not worth having.
        from flux_llm import local_proposer

        brief_ask = a_proposer(timeout_s=CONCLUSION_TIMEOUT_S)
        drawn = draft_conclusions(ranked, brief_ask, model=LLM_MODEL, limit=limit,
                                  scope=f"the interconnect study in {Path(db).name}")
        if not drawn:
            print("    (no lessons: the model drew no conclusion that survived validation)")
            return []
        with FactStore(fact_store_path(db)) as store:
            store_conclusions(store, drawn, scope=f"interconnect study, {Path(db).name}")
        return [c.statement for c in drawn]
    except Exception as exc:  # noqa: BLE001
        print(f"    (no lessons recorded: {type(exc).__name__}: {str(exc)[:60]})")
        return []


def already_enumerated(db: str) -> list[str]:
    """The `enumerate` variants this store has already completed, for THIS problem.

    A family, once enumerated, cannot yield again: the enumeration is a pure function of
    (clients, banks, width) and its output is already in the store. Re-running it re-derives
    thousands of topologies to rediscover fabrics the store holds — 38% of one measured run,
    for nothing (D317). The campaign ids carry the problem and the round, so what has been done
    is recoverable and needs no new table.

    Only a NUMERIC round counts. `round7-hybrid` is an enumeration of the hybrid family;
    `rounda4-staged` and `roundp5-staged` are an anneal and a perturbation that merely inherited
    a family tag from the objective document. Reading those as enumerations would retire families
    nobody had enumerated, which is worse than the repetition being fixed.

    Scoped by the problem deliberately: a store reused for a different client or bank count has
    genuinely enumerated nothing, and must not be told otherwise.
    """
    import sqlite3

    prefix = f"demo/interconnect-{CLIENTS}c-{BANKS}b-{WIDTH_BITS}bit/"
    done: set[str] = set()
    try:
        con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
        try:
            ids = [row[0] for row in con.execute("select objective_json from campaigns")]
        finally:
            con.close()
    except sqlite3.Error:  # a store we cannot read has done nothing yet
        return []
    for raw in ids:
        try:
            ident = str(json.loads(raw).get("id", ""))
        except ValueError:
            continue
        if not ident.startswith(prefix):
            continue
        parts = ident[len(prefix):].split("/")
        if not parts or not parts[0].startswith("round"):
            continue
        round_id, _, family = parts[0][len("round"):].partition("-")
        if round_id.isdigit() and family in SCOPE_KEYS:
            # The BARE family name, because that is what `enumerate`'s `variant_key` returns
            # (`lambda p: p["family"]`). An earlier version returned "enumerated:<family>", which
            # matched nothing in `_done` — the run printed "resuming: 5 of 5 families already
            # enumerated" and then re-enumerated two of them (D323).
            done.add(family)
    return sorted(done)


