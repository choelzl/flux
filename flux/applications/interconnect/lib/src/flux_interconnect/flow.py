"""DEMO: 28 clients x 128b -> 32 banks, concurrent access, minimize area at >= 600 MHz.

Run it (a local model proposes; every candidate's RTL is generated by code, and every number
comes from a real tool):

    nix develop .#physical --command python3 applications/interconnect/demo.py
    nix develop .#physical --command python3 applications/interconnect/demo.py --llm-round 0  # no model

What it does, using this repo's own machinery end to end (docs/decisions.md D261):

  1. Builds an Objective IR document: minimize area, maximize concurrent throughput, with a
     hard constraint of fmax >= 600 MHz, over a space of interconnect topologies.
  2. SCREENS every topology with the instant structural evaluator (mux-bit proxy, peak
     concurrency, expected served-per-cycle under uniform traffic including bank conflicts).
  3. ESCALATES the survivors to the measured rung, where every reported number is measured
     and none is modelled: real Yosys synthesis and real OpenROAD placement on ASAP7 for
     every distinct arbitrated selector the topology uses (fitted across widths on ONE width
     set shared by all arities, then evaluated at 128 bits), and real Verilator simulation of
     the WHOLE fabric under uniform-random traffic for throughput (docs/decisions.md D266).
  4. Prints the trade-off frontier with the fidelity that produced each number, plus the
     memory the fabric serves (32 banks x 512 rows x 128b) characterized by real CACTI.

The screen's analytic throughput model is kept for ranking the space cheaply, and its error is
characterised rather than assumed: within ~10% of RTL wherever a fabric has one path per
destination, and up to 21% LOW where it has several and the router rotates among them.

Everything is durable: the campaign lives in a SQLite file, so an interrupted run resumes.
"""

